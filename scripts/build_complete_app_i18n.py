# Apply key translations
for key, lang_map in TRANSLATIONS.items():
    for lang, val in lang_map.items():
        # Match pattern within that language block: "key": "..."
        pattern = rf'("{lang}":\s*\{{[\s\S]*?{re.escape(json.dumps(key))}\s*:\s*)(["\'][^"\']*["\'])'
        
        def repl(match):
            return match.group(1) + json.dumps(val, ensure_ascii=False)
        
        new_code = re.sub(pattern, repl, code, count=1)
        if new_code != code:
            code = new_code

